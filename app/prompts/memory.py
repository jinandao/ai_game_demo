"""提示词：记忆压缩与抽取，compact 与 final 共用一套规则。"""

from __future__ import annotations

EXTRACT_RULES = """把下面这段对话压缩成结构化结果。

【先看这一条 —— 决定成败】
这段对话结束后，**原文就没了**。不会被保存，不会留档，以后也查不到。
你抽出来的这几条 facts，就是她关于这段对话**唯一**还记得的东西。
漏掉的，等于没发生过。

所以：**宁可多记，不要漏记。**
抽得少不是"精炼"，是让她忘事。
玩家说过的每一个人名、每一条亲属关系（谁是谁的什么）、每一个偏好和禁忌，
都要**单独成条**。同一句话里说了三件事，就是三条。

【保留】
1. 玩家明确表达的偏好、禁忌、承诺、个人信息
2. 发生过的具体事件及结果
3. 约定、未完成事项 —— 记成 other，并把 promise 设为 true
4. 对话里出现过、之后可能再被提起的设定细节
5. **按对象成条，不按句子切**。不要合并，更不要只抓第一个。
   - 同一句话提到**不同的人**，分别成条：「我妹妹叫小雨，还有个姐姐叫小月」
     → 妹妹一条、姐姐一条。
   - **同一个人的多个属性**，合成一条：「姐姐叫小月，比我大三岁，在九号站」
     → 一条，因为以后问的是"你姐姐是谁"，不会分开问年龄和地址。
   判断标准：**换个人就分开，同一个人就合起来。**

【丢弃】
寒暄、重复内容、已经确认无法推进的话题、纯语气词

【summary 的写法】
- 第三人称陈述，不超过 300 字
- 只写发生过什么、达成了什么、还欠着什么
- 禁止写「玩家和 NPC 聊了很多」这类空话

【facts 的写法】
- subject 只能是三个值：
    event       发生过的行为与经历（去了哪、做了什么、一起干了什么）
    player      玩家自己的信息（偏好 / 禁忌 / 习惯 / 身份）
    other       其它（世界观、地点、规矩、传闻、约定）
- promise 是布尔值：这条是不是「约定 / 答应了但还没做」的事
- key 是去重用的短标签，2~6 个字，同类事情要用同一个 key
- value 一句话说清，不要写"玩家表示""NPC 提到"这种转述腔
- **value 里必须写清楚关系词**：「玩家姐姐叫小月」而不是「小月」。
  只记名字不记关系，下次会把"你的姐姐"说成"我的妹妹"——
  这是最容易发生的一种错，因为名字记住了，关系是空的
- importance 1~5：5 = 关系到信任或承诺，3 = 有用的信息，1 = 闲聊细节
- evidence 必须是原文里的原句片段，用来核对。找不到原句就不要写这条
- 不得发明原文没有的人名、地名、组织名、数字

【promise 的界线】
只有「对方明确答应过」或「双方明确约好」的事，才写 promise=true。
玩家随口一提的想法不算约定 —— 把随口一提记成约定，
下次她会拿着这句话来逼玩家兑现，观感会非常差。

【affection_hint】
只在有明确依据时给：玩家帮了忙、守了约、说了伤人的话。
delta 建议 -3 ~ +5。理由一句话。没有就留空数组。

【输出示范 —— 照这个粒度抽】

输入对话：
玩家：我妹妹叫小雨，跟我妈住。我还有个姐姐叫小月，比我大三岁，在九号站。
你：九号站啊……那边靠河，日子比咱们好过。
玩家：我最近总失眠，一躺下就听见外面有动静。

输出：
{
  "summary": "玩家提到家里的情况：妹妹小雨跟母亲住，姐姐小月比他大三岁、人在九号站。还说最近失眠，躺下能听见外面的动静。",
  "facts": [
    {"subject": "player", "key": "妹妹信息", "value": "玩家妹妹叫小雨，跟母亲一起住", "importance": 3, "evidence": "我妹妹叫小雨，跟我妈住"},
    {"subject": "player", "key": "姐姐信息", "value": "玩家姐姐叫小月，比他大三岁，在九号站", "importance": 4, "evidence": "我还有个姐姐叫小月，比我大三岁，在九号站"},
    {"subject": "player", "key": "睡眠状况", "value": "玩家最近失眠，躺下能听见外面有动静", "importance": 3, "evidence": "我最近总失眠，一躺下就听见外面有动静"}
  ],
  "affection_hint": []
}

看清楚这三件事：
1. 一句话里两个亲属，抽成了**两条**（妹妹、姐姐），不是一个笼统的"家庭情况"；
2. 同一个人的多个属性**合成一条**（姐姐的名字、年龄、所在地都在一条里）；
3. 那句"最近总失眠"看着像随口抱怨，但它**也是玩家的信息**，照样抽出来——
   下次她可以问"昨晚睡得怎么样"，这就是有记忆的样子。
   只抽"正式的自我介绍"、漏掉顺口说的事，是最常见的漏法。"""

MODE_NOTE = {
    "compact": "注意：这段是要被压缩掉的中段对话。更早的摘要已经给在上面，"
    "只把它当背景，不要把它的内容重复写进新的 summary。",
    "final": "注意：这是会话收尾的抽取。上面可能包含还没被整理过的新对话，"
    "也会有已经抽过的部分 —— 只处理还没整理的内容，不要重复记录。",
}


def build_extract_system(mode: str) -> str:
    return EXTRACT_RULES + "\n\n" + MODE_NOTE.get(mode, "")


def build_extract_user(transcript: str, last_summary: str | None) -> str:
    parts: list[str] = []
    if last_summary:
        parts.append("【更早的对话摘要 · 仅作背景】")
        parts.append(last_summary)
        parts.append("")
    parts.append("【要处理的对话】")
    parts.append(transcript)
    return "\n".join(parts)
