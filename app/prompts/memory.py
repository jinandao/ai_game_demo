"""提示词：记忆压缩与抽取。"""

from __future__ import annotations

EXTRACT_RULES = """把下面这段对话压缩成结构化结果。

【先看这一条 —— 决定成败】
这段对话结束后，**原文就没了**。不会被保存，不会留档，以后也查不到。
你抽出来的这几条 facts，就是她关于这段对话**唯一**还记得的东西。
漏掉的，等于没发生过。

所以：**宁可多记，不要漏记。**
抽得少不是"精炼"，是让她忘事。
玩家说过的每一个人名、每一条亲属关系（谁是谁的什么）、每一个偏好和禁忌，
都要**单独成条**。同一句话里说了三件事，就是三条。

【保留】
1. 玩家明确表达的偏好、禁忌、承诺、个人信息
2. 发生过的具体事件及结果
3. 约定、未完成事项 —— 记成 other，并把 promise 设为 true
4. 对话里出现过、之后可能再被提起的设定细节
5. **一条只装一件信息，别把几件事挤进同一个 value。**
   - 「我妹妹叫小雨，跟我妈住」→ 两条：妹妹叫什么、妹妹跟谁住。
   - 「姐姐叫小月，比我大三岁，在九号站」→ 三条。
   - 为什么：检索是**每条各自**跟问题算相似度。一条里塞三件事，
     问"姐姐多大"的时候会连住址一起端出来，也更容易答错人。
   - 判断标准：**一句话能拆出几个「谁 / 什么」，就是几条。**

【丢弃】
寒暄、重复内容、已经确认无法推进的话题、纯语气词

【summary 的写法】
- 第三人称陈述，不超过 300 字
- 只写发生过什么、达成了什么、还欠着什么
- 禁止写「玩家和 NPC 聊了很多」这类空话

【facts 的写法】
- subject 只能是三个值：
    event       发生过的行为与经历（去了哪、做了什么、一起干了什么）
    player      玩家自己的信息（偏好 / 禁忌 / 习惯 / 身份）
    other       其它（世界观、地点、规矩、传闻、约定）
- promise 是布尔值：这条是不是「约定 / 答应了但还没做」的事
- key 是**分类**，2~6 个字。同一个分类下可以有很多条，谁也不顶掉谁：
  「家庭成员」「偏好」「禁忌」「约定」「作息」「经历」「站里的规矩」。
  - 它只是方便翻找用，**不参与检索打分**——写成「姐姐住址」这种过细的 key
    没有意义，妹妹和姐姐都归「家庭成员」就行。
  - 同一个分类下可以有很多条，直接写就行，**不用管重不重复**——存储不合并，
    按 key 分组出来就是一个分类挂着一串信息。
- value 一句话说清，不要写"玩家表示""NPC 提到"这种转述腔
- **value 里必须写清楚关系词**：「玩家姐姐叫小月」而不是「小月」。
  只记名字不记关系，下次会把"你的姐姐"说成"我的妹妹"——
  这是最容易发生的一种错，因为名字记住了，关系是空的
- importance 1~5：5 = 关系到信任或承诺，3 = 有用的信息，1 = 闲聊细节
- evidence 必须是原文里的原句片段，用来核对。找不到原句就不要写这条
- 不得发明原文没有的人名、地名、组织名、数字

【promise 的界线】
只有「对方明确答应过」或「双方明确约好」的事，才写 promise=true。
玩家随口一提的想法不算约定 —— 把随口一提记成约定，
下次她会拿着这句话来逼玩家兑现，观感会非常差。

【affection_hint】
只在有明确依据时给：玩家帮了忙、守了约、说了伤人的话。
delta 建议 -3 ~ +5。理由一句话。没有就留空数组。

【输出示范 —— 照这个粒度抽】

输入对话：
玩家：我妹妹叫小雨，跟我妈住。我还有个姐姐叫小月，比我大三岁，在九号站。
你：九号站啊……那边靠河，日子比咱们好过。
玩家：我最近总失眠，一躺下就听见外面有动静。

输出：
{
  "summary": "玩家提到家里的情况：妹妹小雨跟母亲住，姐姐小月比他大三岁、人在九号站。还说最近失眠，躺下能听见外面的动静。",
  "facts": [
    {"subject": "player", "key": "家庭成员", "value": "玩家妹妹叫小雨", "importance": 3, "evidence": "我妹妹叫小雨"},
    {"subject": "player", "key": "家庭成员", "value": "玩家妹妹跟他母亲一起住", "importance": 3, "evidence": "跟我妈住"},
    {"subject": "player", "key": "家庭成员", "value": "玩家姐姐叫小月", "importance": 4, "evidence": "我还有个姐姐叫小月"},
    {"subject": "player", "key": "家庭成员", "value": "玩家姐姐比他大三岁", "importance": 3, "evidence": "比我大三岁"},
    {"subject": "player", "key": "家庭成员", "value": "玩家姐姐在九号站", "importance": 4, "evidence": "在九号站"},
    {"subject": "player", "key": "作息", "value": "玩家最近失眠，躺下能听见外面有动静", "importance": 3, "evidence": "我最近总失眠，一躺下就听见外面有动静"}
  ],
  "affection_hint": []
}

看清楚这四件事：
1. 姐姐妹妹都在「家庭成员」这一个分类里，**五条并存**，谁也不覆盖谁——
   分类只是抽屉，同一个抽屉里放几样东西都行。
2. 姐姐的名字、年龄、住址**拆成三条**，不是一条。检索是一条一条算相似度的，
   问"姐姐多大"时才会精准命中年份那条，不会把住址一起端出来。
3. 每条 value 都**自带主语和关系**（「玩家姐姐」「玩家妹妹」），
   因为同一个抽屉里躺着好几条，只写「小雨」就不知道是谁的什么人。
4. 那句"最近总失眠"看着像随口抱怨，但它**也是玩家的信息**，照样抽出来——
   下次她可以问"昨晚睡得怎么样"，这就是有记忆的样子。
   只抽"正式的自我介绍"、漏掉顺口说的事，是最常见的漏法。"""

MODE_NOTE = {
    "compact": "注意：这段是要被压缩掉的中段对话。更早的摘要已经给在上面，"
    "只把它当背景，不要把它的内容重复写进新的 summary。",
    "final": "注意：这是会话收尾的抽取。上面可能包含还没被整理过的新对话，"
    "也会有已经抽过的部分 —— 只处理还没整理的内容，不要重复记录。",
}

def build_extract_system(mode: str) -> str:
    return EXTRACT_RULES + "\n\n" + MODE_NOTE.get(mode, "")

def build_extract_user(transcript: str, last_summary: str | None) -> str:
    parts: list[str] = []
    if last_summary:
        parts.append("【更早的对话摘要 · 仅作背景】")
        parts.append(last_summary)
        parts.append("")
    parts.append("【要处理的对话】")
    parts.append(transcript)
    return "\n".join(parts)
